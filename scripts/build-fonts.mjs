// Prepares fonts/ and src/fonts/generated.ts:
//  - copies the Pretendard dynamic-subset woff2 files (Medium 500, SemiBold 600) so SVGs can embed
//    only the chunks a diagram actually uses
//  - measures glyph advance widths for Pretendard (SVG/PNG) and Nunito (Excalidraw's sans) in Chromium
// Run: node scripts/build-fonts.mjs   (needs devDependencies pretendard, @fontsource/nunito, playwright)
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);
const pretendardDir = new URL('node_modules/pretendard/dist/web/static/', root);
const css = readFileSync(new URL('pretendard-dynamic-subset.css', pretendardDir), 'utf8');

const WEIGHTS = { 500: 'Medium' };
const outDir = new URL('fonts/pretendard/', root);
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

// ---- subsets ----
const subsets = {};
for (const block of css.split('@font-face').slice(1)) {
  const weight = /font-weight:\s*(\d+)/.exec(block)?.[1];
  if (!WEIGHTS[weight]) continue;
  const file = /url\(\.\/woff2-dynamic-subset\/([^)]+\.woff2)\)/.exec(block)[1];
  const ranges = /unicode-range:\s*([^;]+);/.exec(block)[1].split(',').map((r) => r.trim().replace(/^U\+/i, '')).map((r) => {
    const [a, b] = r.split('-');
    return [parseInt(a, 16), parseInt(b ?? a, 16)];
  });
  copyFileSync(new URL(`woff2-dynamic-subset/${file}`, pretendardDir), new URL(file, outDir));
  (subsets[weight] ??= []).push({ file, ranges });
}
const header = /\/\*([\s\S]*?)\*\//.exec(css)[1].trim();
copyFileSync(new URL('node_modules/pretendard/dist/LICENSE.txt', root), new URL('LICENSE.txt', outDir));
void header;

// ---- metrics ----
const { chromium } = require('playwright');
const b64 = (u) => readFileSync(u).toString('base64');
const faces = [
  `@font-face{font-family:'P500';src:url(data:font/woff2;base64,${b64(new URL('woff2/Pretendard-Medium.woff2', pretendardDir))})}`,
  `@font-face{font-family:'P600';src:url(data:font/woff2;base64,${b64(new URL('woff2/Pretendard-SemiBold.woff2', pretendardDir))})}`,
  `@font-face{font-family:'Nunito';src:url(data:font/woff2;base64,${b64(new URL('node_modules/@fontsource/nunito/files/nunito-latin-400-normal.woff2', root))})}`,
].join('');
const chars = [];
for (let c = 32; c < 127; c++) chars.push(String.fromCharCode(c));
for (let c = 0xa0; c <= 0xff; c++) chars.push(String.fromCharCode(c));
chars.push('–', '—', '’', '“', '”', '…', '→', '•', '·');
const browser = await chromium.launch(process.env.DRAFTR_CHROMIUM ? { executablePath: process.env.DRAFTR_CHROMIUM } : {});
const page = await browser.newPage();
await page.setContent(`<style>${faces}</style><span style="font-family:P500">a</span><span style="font-family:P600">a</span><span style="font-family:Nunito">a</span>`);
await page.evaluate(() => document.fonts.ready);
const metrics = await page.evaluate(({ chars }) => {
  const ctx = document.createElement('canvas').getContext('2d');
  const out = {};
  for (const fam of ['P500', 'P600', 'Nunito']) {
    ctx.font = `1000px ${fam}`;
    const table = {};
    for (const ch of chars) table[ch] = Math.round(ctx.measureText(ch).width) / 1000;
    out[fam] = { table, hangul: Math.round(ctx.measureText('한').width) / 1000, fallback: Math.round(ctx.measureText('n').width) / 1000 };
  }
  return out;
}, { chars });
await browser.close();

const ts = `// GENERATED by scripts/build-fonts.mjs — do not edit by hand.
/* eslint-disable */
/** Pretendard dynamic subsets shipped in fonts/pretendard: weight -> files with their unicode ranges. */
export const PRETENDARD_SUBSETS: Record<number, Array<{ file: string; ranges: Array<[number, number]> }>> = ${JSON.stringify(subsets)};
/** Advance widths in em. hangul: width of a Hangul syllable; fallback: used for characters not in the table. */
export const METRICS: Record<'pretendard500' | 'pretendard600' | 'nunito', { table: Record<string, number>; hangul: number; fallback: number }> = ${JSON.stringify({ pretendard500: metrics.P500, pretendard600: metrics.P600, nunito: { ...metrics.Nunito, hangul: 1 } })};
`;
writeFileSync(new URL('src/fonts/generated.ts', root), ts);
console.log(`subsets: ${Object.entries(subsets).map(([w, s]) => `${w}:${s.length}`).join(' ')}; metrics: ${chars.length} chars`);
